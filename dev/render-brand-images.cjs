/* DEV ONLY. Delete before launch (see README).
   Rebuilds the brand images from the logo mark chosen in js/site-config.js
   (images.logoMark):
     images/favicon.svg          mark on a cream rounded square
     images/og-image.svg         1200x630 share image source
     images/og-image.png         1200x630 PNG (social sites ignore SVG)
     images/apple-touch-icon.png 180x180 PNG
   Needs Node and Playwright, which are NOT part of the site:
     NODE_PATH="$(npm root -g)" node dev/render-brand-images.cjs
   Install the Fraunces and Nunito fonts locally first, or the PNG falls
   back to Georgia / a system sans. */
'use strict';
const fs = require('fs');
const path = require('path');
const vm = require('vm');
const { chromium } = require('playwright');

const root = path.resolve(__dirname, '..');
const sandbox = { window: {} };
vm.runInNewContext(fs.readFileSync(path.join(root, 'js/site-config.js'), 'utf8'), sandbox);
const C = sandbox.window.SITE_CONFIG;
const markFile = path.join(root, C.images.logoMark);
const markSvg = fs.readFileSync(markFile, 'utf8');
/* The drawable part of the mark: everything inside <svg>, minus <title> and comments. */
const inner = markSvg
  .replace(/^[\s\S]*?<svg[^>]*>/, '')
  .replace(/<\/svg>\s*$/, '')
  .replace(/<title[\s\S]*?<\/title>/, '')
  .replace(/<!--[\s\S]*?-->/g, '')
  .trim();

const favicon = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64" width="64" height="64">
  <!-- Generated by dev/render-brand-images.cjs from ${C.images.logoMark}. -->
  <rect width="64" height="64" rx="14" fill="#FFF8EE"/>
  <g transform="translate(4 4) scale(0.875)">
    ${inner}
  </g>
</svg>
`;

const og = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1200 630" width="1200" height="630">
  <!-- Generated by dev/render-brand-images.cjs from ${C.images.logoMark}. Source for og-image.png. -->
  <rect width="1200" height="630" fill="#FFF8EE"/>
  <circle cx="1080" cy="90" r="230" fill="#FCE9CF"/>
  <circle cx="1120" cy="560" r="110" fill="#F2A541" opacity="0.35"/>
  <g transform="translate(80 175) scale(4.4)">
    ${inner}
  </g>
  <text x="400" y="270" font-family="Fraunces, Georgia, 'Times New Roman', serif" font-size="96" font-weight="800" fill="#5A1F1B">${C.orgName}</text>
  <text x="404" y="342" font-family="Fraunces, Georgia, 'Times New Roman', serif" font-size="44" font-weight="600" fill="#B84A33">${C.tagline}</text>
  <text x="404" y="420" font-family="Nunito, Helvetica, Arial, sans-serif" font-size="30" font-weight="700" fill="#3B2A24">Free online tutoring in Telugu and English</text>
  <text x="404" y="462" font-family="Nunito, Helvetica, Arial, sans-serif" font-size="30" font-weight="700" fill="#3B2A24">for 4th and 5th graders in Hyderabad and Vijayawada</text>
</svg>
`;

const touch = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64" width="180" height="180">
  <rect width="64" height="64" fill="#FFF8EE"/>
  <g transform="translate(9 9) scale(0.72)">${inner}</g>
</svg>`;

(async () => {
  fs.writeFileSync(path.join(root, 'images/favicon.svg'), favicon);
  fs.writeFileSync(path.join(root, 'images/og-image.svg'), og);
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 1200, height: 630 } });
  await page.setContent(`<html><body style="margin:0">${og}</body></html>`);
  await page.evaluate(() => document.fonts.ready);
  await page.screenshot({ path: path.join(root, 'images/og-image.png') });
  await page.setViewportSize({ width: 180, height: 180 });
  await page.setContent(`<html><body style="margin:0">${touch}</body></html>`);
  await page.screenshot({ path: path.join(root, 'images/apple-touch-icon.png') });
  await browser.close();
  console.log('Rendered brand images from ' + C.images.logoMark);
})();
